import assert from 'node:assert/strict';
import {parseKakaoCommand,publishedTrainings,selectKakaoTraining,trainingSummary} from '../lib/kakao.ts';
import {initialState} from '../lib/domain.ts';
assert.deepEqual(parseKakaoCommand('!yes 2099-11-02'),{kind:'rsvp',value:'참석',selector:'2099-11-02'});
assert.deepEqual(parseKakaoCommand('!불참'),{kind:'rsvp',value:'불참',selector:''});
assert.equal(parseKakaoCommand('ordinary message'),null);
assert.equal(parseKakaoCommand('!연결 bad-code'),null);
const state=initialState('Test','Captain');state.members=state.members.slice(0,2);
state.trainingManuals=[{id:'ab',title:'AB',titleEn:'AB drill',minimum:3,goal:'Practice',steps:'Defenders behind setter',diagram:'ab',updatedAt:''}];
const event={id:'a',title:'Practice',date:'2099-11-02',time:'18:30',endTime:'20:00',location:'Court',kind:'정기 훈련',manualIds:['ab'],note:'',attendance:{m1:'참석'}};
state.events=[event,{...event,id:'unpublished',manualIds:undefined}];
assert.equal(publishedTrainings(state,'2099-11-02').length,1);
assert.equal(selectKakaoTraining(state,'','2099-11-02').id,'a');
state.events.push({...event,id:'b',date:'2099-11-03'});
assert.throws(()=>selectKakaoTraining(state,'','2099-11-02'));
assert.equal(selectKakaoTraining(state,'2099-11-03','2099-11-02').id,'b');
const summary=trainingSummary(state,event,'https://club.example');assert.ok(summary.attendance.includes('Yes 1'));assert.ok(summary.guide.includes('Defenders behind setter'));
assert.ok(summary.url.includes('event=a'));
console.log('PASS: bilingual Kakao commands, explicit session selection, shared RSVP summaries and guide links');
